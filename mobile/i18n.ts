export const DEFAULT_LANG: Lang = "en";
const LANG_KEY = "freesurf-app-lang";

// Languages we translate but do NOT offer in the Transcriber: Whisper's transcription
// quality is currently too poor for them, and the app uses the UI language as the
// transcription language. Re-enable once accuracy improves.
export const UNSUPPORTED: ReadonlySet<string> = new Set([
  "bn", // Bengali
  "da", // Danish
  "id", // Indonesian
  "ms", // Malay
  "mr", // Marathi
  "no", // Norwegian
  "fa", // Persian
  "ro", // Romanian
  "sv", // Swedish
  "ta", // Tamil
  "th", // Thai
  "ha", // Hausa
]);

/** Return the language code if we translate and support it, otherwise English. */
export function normalizeLang(code?: string | null): Lang {
  if (code && translations[code] && !UNSUPPORTED.has(code)) return code;
  return DEFAULT_LANG;
}

export function deviceLang(): Lang {
  try {
    return normalizeLang(getLocales()?.[0]?.languageCode);
  } catch {
    return DEFAULT_LANG;
  }
}

export function translationsFor(lang: Lang): Strings {
  const en = translations[DEFAULT_LANG] ?? {};
  return { ...en, ...(translations[lang] ?? {}) };
}

// Module-level shared language state so every component that calls useAppLanguage()
// re-renders when the language changes (dashboard, menus, paywall, etc.).
let currentCode: string | null = null;
let loadedFlag = false;
let loadPromise: Promise<void> | null = null;
const listeners = new Set<() => void>();

function emit() {
  listeners.forEach((l) => l());
}

function ensureLoaded() {
  if (loadPromise) return loadPromise;
  loadPromise = AsyncStorage.getItem(LANG_KEY)
    .then((v) => { if (v) currentCode = v; })
    .catch(() => {})
    .finally(() => { loadedFlag = true; emit(); });
  return loadPromise;
}

export function setAppLanguage(code: string) {
  currentCode = code;
  AsyncStorage.setItem(LANG_KEY, code).catch(() => {});
  emit();
}

/**
 * Returns the active language (device locale by default) plus a persisted override.
 * `chosen` is true only once the user has explicitly picked a language (so the first-launch
 * chooser shows until then). The stored value is the raw code (e.g. "hi"); the UI falls back to
 * English for languages we haven't translated yet.
 */
export function useAppLanguage(): {
  lang: Lang;
  loaded: boolean;
  chosen: boolean;
  chosenCode: string | null;
  setLanguage: (code: string) => void;
} {
  const [, force] = useState(0);
  useEffect(() => {
    ensureLoaded();
    const listener = () => force((n) => n + 1);
    listeners.add(listener);
    return () => { listeners.delete(listener); };
  }, []);
  const lang = normalizeLang(currentCode ?? deviceLang());
  return {
    lang,
    loaded: loadedFlag,
    chosen: loadedFlag && currentCode !== null,
    chosenCode: currentCode,
    setLanguage: setAppLanguage,
  };
}
